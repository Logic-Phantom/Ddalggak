import Ionicons from '@expo/vector-icons/Ionicons';
import { useState } from 'react';
import { Pressable, StyleSheet, View } from 'react-native';

import { AppText, Card, Divider, ScreenScroll, radius, spacing, useColors } from '@/design-system';
import notices from '@/generated/oss-licenses.json';

interface Notice {
  name: string;
  version: string;
  license: string;
  copyright: string[];
  textId: string | null;
}

const PACKAGES = notices.packages as Notice[];
const TEXTS = notices.texts as Record<string, string>;

function NoticeRow({ notice }: { notice: Notice }) {
  const c = useColors();
  const [open, setOpen] = useState(false);
  const text = notice.textId ? TEXTS[notice.textId] : null;
  return (
    <View>
      <Pressable
        onPress={() => setOpen((v) => !v)}
        accessibilityRole="button"
        accessibilityState={{ expanded: open }}
        accessibilityLabel={`${notice.name}, ${notice.license}`}
        style={({ pressed }) => [styles.head, pressed && { backgroundColor: c.surfaceSunken }]}>
        <View style={{ flex: 1, gap: 2 }}>
          <AppText variant="body">{notice.name}</AppText>
          <AppText variant="caption" tone="tertiary">{notice.version ? `${notice.version} · ` : ''}{notice.license}</AppText>
        </View>
        <Ionicons name={open ? 'chevron-up' : 'chevron-down'} size={18} color={c.textSecondary} />
      </Pressable>
      {open ? (
        <View style={[styles.text, { backgroundColor: c.surfaceSunken }]}>
          {notice.copyright.map((line) => (
            <AppText key={line} variant="caption" tone="secondary" selectable>{line}</AppText>
          ))}
          {text ? <AppText variant="caption" tone="secondary" selectable>{text}</AppText> : null}
        </View>
      ) : null}
    </View>
  );
}

/** Open source notices for every package shipped in the app bundle (generated by scripts/license-audit.mjs). */
export default function LicensesScreen() {
  return (
    <ScreenScroll>
      <AppText variant="secondary" tone="secondary">킵온은 아래 오픈소스 소프트웨어를 사용해요. 항목을 누르면 저작권 표시와 라이선스 전문을 볼 수 있어요.</AppText>
      <Card padded={false}>
        {PACKAGES.map((p, i) => (
          <View key={`${p.name}@${p.version}`}>
            {i ? <Divider inset={spacing.md} /> : null}
            <NoticeRow notice={p} />
          </View>
        ))}
      </Card>
    </ScreenScroll>
  );
}

const styles = StyleSheet.create({
  head: { flexDirection: 'row', alignItems: 'center', gap: spacing.sm, paddingHorizontal: spacing.md, paddingVertical: spacing.sm, minHeight: 56 },
  text: { gap: spacing.xs, marginHorizontal: spacing.md, marginBottom: spacing.sm, padding: spacing.sm, borderRadius: radius.button },
});
